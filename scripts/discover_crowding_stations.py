"""Write config/crowding_stations.yaml: every Tube station, for live busyness.

A one-off helper (ADR-019), not run in CI. It lists the stations of each Tube
line in config/lines.yaml from ``Line/{id}/StopPoints`` and keeps the
station-level 940GZZLU ids, which ``crowding/{naptan}/Live`` accepts. It calls
the TfL API anonymously (no key is read) and sleeps between requests.

Re-run it when a Tube station opens or closes, review the diff, and commit.

Usage:
    uv run python scripts/discover_crowding_stations.py
"""

import time
from datetime import UTC, datetime
from typing import Any

import httpx
import yaml

from mind_the_data.common.config import Mode, default_config_dir, load_config

BASE_URL = "https://api.tfl.gov.uk"
PAUSE_SECONDS = 3.0
TUBE_PREFIX = "940GZZLU"
OUT = default_config_dir() / "crowding_stations.yaml"

HEADER = """\
# Stations whose live busyness (crowding/{naptan_id}/Live) is collected, ADR-019.
#
# Every Tube station: the station-level 940GZZLU ids from Line/{id}/StopPoints
# for each Tube line in lines.yaml. Generated by
# scripts/discover_crowding_stations.py on %s; re-run it when a station
# opens or closes. Each station is read once every 5 minutes, a fifth of the
# list each minute (ingest/context.py), so the list's length sets the request
# rate: %d stations is about %d calls a minute.
"""


def tube_stations(client: httpx.Client, line_id: str) -> dict[str, str]:
    response = client.get(f"/Line/{line_id}/StopPoints")
    response.raise_for_status()
    stops: list[dict[str, Any]] = response.json()
    return {
        stop["naptanId"]: stop["commonName"]
        for stop in stops
        if str(stop.get("naptanId", "")).startswith(TUBE_PREFIX)
    }


def main() -> int:
    lines, _ = load_config()
    found: dict[str, str] = {}
    headers = {"User-Agent": "mind-the-data station discovery"}
    with httpx.Client(base_url=BASE_URL, headers=headers, timeout=30.0) as client:
        for index, line in enumerate(line for line in lines if line.mode is Mode.TUBE):
            if index:
                time.sleep(PAUSE_SECONDS)
            found.update(tube_stations(client, line.id))
    stations = [{"naptan_id": k, "name": found[k]} for k in sorted(found)]
    body = yaml.safe_dump({"stations": stations}, sort_keys=False, allow_unicode=True)
    stamp = datetime.now(UTC).strftime("%Y-%m-%d")
    rate = -(-len(stations) // 5)
    OUT.write_text(HEADER % (stamp, len(stations), rate) + "\n" + body)
    print(f"{OUT}: {len(stations)} stations")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
